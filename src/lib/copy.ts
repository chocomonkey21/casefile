/*
  All interface text lives here, so wording can be edited in one place.

  Tone: a calm, clear learning platform. Warm and encouraging, like a good teacher talking to an
  11 to 15 year old. Short sentences, no slang, no game language (no points, credits or "unlocked!"),
  and no em dashes. At most one exclamation mark per screen, and only for a real milestone.
  Every name a student acts on is a plain word, taken from lib/labels.ts (Home, Lesson, Study material,
  Quiz, Final test, Study board, Notes, My progress). The detective theme stays in the look and in "Case".

  Lesson and quiz content (readings, questions, hints, explanations) is course content, not interface
  text. It lives in src/data.
*/

