// Writes src/data/curriculum/meta.generated.ts: the chapter and lesson lists for the new chapters, without any lesson text.
// Browser code reads this small file. The lesson text stays in the server-only chapter files.
// Run with: npm run gen:curriculum   (npm run check:curriculum fails if this file is out of date)
import { writeFileSync } from "node:fs";
import { cleanup, compileData } from "./lib/compile-data.mjs";

const load = compileData();
const { NEW_CASES, TOP_UP_CLUES } = load("data/curriculum/specs.js");
const text = `import type { CaseDef, ClueDef } from "@/lib/types";

/*
  GENERATED by \`npm run gen:curriculum\` from the chapter files in this folder. Do not edit by hand.
  It holds only the chapter and lesson lists (no lesson text), so browser code can use it without
  downloading every lesson. The lesson text is in specs.ts, which only server code imports.
*/
export const NEW_CASES: CaseDef[] = ${JSON.stringify(NEW_CASES, null, 1)};

export const TOP_UP_CLUES: Record<string, ClueDef[]> = ${JSON.stringify(TOP_UP_CLUES, null, 1)};
`;
writeFileSync("src/data/curriculum/meta.generated.ts", text);
cleanup();
console.log(`Wrote src/data/curriculum/meta.generated.ts (${NEW_CASES.length} chapters, ${Object.values(TOP_UP_CLUES).flat().length} top-up lessons).`);
